import html
import re
import sys

page = open(sys.argv[1], encoding="utf-8", errors="replace").read()
select = page[page.index('id="inputZone"'):]
select = select[:select.index("</select>")]
rows = []
for group, body in re.findall(r'<optgroup label="([^"]+)">(.*?)</optgroup>', select, re.S):
    for code, text in re.findall(r"<option value='([A-Z]{3}\d{2})'[^>]*>([^<]+)</option>", body):
        name = html.unescape(text).split(" - ", 1)[1].strip()
        rows.append((code, html.unescape(group).strip(), name))
if len(rows) < 50 or not any(code == "SGR03" for code, _, _ in rows):
    sys.exit(f"unexpected zone list: {len(rows)} zones")

def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["// Generated by tools/gen_zones.py from the e-solat zone picker. Do not edit.",
       '#include "zones.h"', "", "const zone_t ZONES[] = {"]
out += [f"    {{{c(code)}, {c(state)}, {c(name)}}}," for code, state, name in rows]
out += ["};", f"const size_t ZONE_COUNT = {len(rows)};", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(f"{len(rows)} zones")
